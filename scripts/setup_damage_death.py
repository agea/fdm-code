"""Configure owned impact audio and team corpse through Unreal Editor."""
import unreal as ue
assets = ue.EditorAssetLibrary
tools = ue.AssetToolsHelpers.get_asset_tools()
audio_folder = '/Game/EclipseRecoil/Audio'
assets.make_directory(audio_folder)
task = ue.AssetImportTask()
task.set_editor_property('filename', '/private/tmp/ER_Hit_Impact.wav')
task.set_editor_property('destination_path', audio_folder)
task.set_editor_property('destination_name', 'S_ER_Hit_Impact')
task.set_editor_property('automated', True)
task.set_editor_property('replace_existing', True)
task.set_editor_property('save', True)
tools.import_asset_tasks([task])
sound = ue.load_asset(audio_folder + '/S_ER_Hit_Impact')
if not sound: raise RuntimeError('Cannot import hit sound')
att = ue.load_asset(audio_folder + '/SA_ER_Hit') or tools.create_asset('SA_ER_Hit', audio_folder, ue.SoundAttenuation, ue.SoundAttenuationFactory())
settings = att.get_editor_property('attenuation')
settings.set_editor_property('spatialize', True)
settings.set_editor_property('attenuation_shape_extents', ue.Vector(200, 0, 0))
settings.set_editor_property('falloff_distance', 600)
att.set_editor_property('attenuation', settings)
assets.save_loaded_asset(att, False)
target = ue.get_default_object(ue.load_asset('/Game/EclipseRecoil/Core/BP_ERTrainingTarget').generated_class())
appearance = target.alpha_skins[0]
mesh = appearance.mesh
physics = mesh.get_editor_property('physics_asset')
if not physics:
    physics = ue.load_asset('/Game/Characters/Mannequins/Rigs/PA_Mannequin')
if not physics: raise RuntimeError('No ragdoll physics asset available')
bp = ue.load_asset('/Game/EclipseRecoil/Core/BP_ERCorpse')
if not bp:
    factory = ue.BlueprintFactory(); factory.set_editor_property('parent_class', ue.ERCorpse)
    bp = tools.create_asset('BP_ERCorpse', '/Game/EclipseRecoil/Core', ue.Blueprint, factory)
defaults = ue.get_default_object(bp.generated_class())
body = defaults.get_editor_property('body')
body.set_skeletal_mesh_asset(mesh)
body.set_physics_asset(physics, True)
body.set_editor_property('relative_location', ue.Vector(0, 0, -92.5))
body.set_editor_property('relative_rotation', ue.Rotator(pitch=0, yaw=-90, roll=0))
body.set_editor_property('relative_scale3d', ue.Vector(appearance.scale, appearance.scale, appearance.scale))
body.set_editor_property('animation_mode', ue.AnimationMode.ANIMATION_SINGLE_NODE)
anim = body.get_editor_property('animation_data')
anim.set_editor_property('anim_to_play', appearance.corpse_pose)
anim.set_editor_property('saved_looping', True)
body.set_editor_property('animation_data', anim)
defaults.set_editor_property('alpha_materials', [])
defaults.set_editor_property('omega_materials', [])
ue.BlueprintEditorLibrary.compile_blueprint(bp)
assets.save_loaded_asset(bp, False)
for path in ['/Game/EclipseRecoil/Core/BP_ERCharacter', '/Game/EclipseRecoil/Core/BP_ERTrainingTarget']:
    character = ue.load_asset(path); cdo = ue.get_default_object(character.generated_class())
    cdo.set_editor_property('corpse_class', bp.generated_class())
    cdo.set_editor_property('hit_sound', sound)
    cdo.set_editor_property('hit_attenuation', att)
    ue.BlueprintEditorLibrary.compile_blueprint(character)
    assets.save_loaded_asset(character, False)
ue.log('ER_DAMAGE_DEATH_ASSETS_READY physics=%s sound=%s corpse=%s' % (physics.get_path_name(), sound.get_path_name(), bp.generated_class().get_path_name()))

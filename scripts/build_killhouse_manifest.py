#!/usr/bin/env python3
"""Author the balanced Killhouse assembly manifest; no Unreal binary writes."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'Assets/maps/SourceAssets/MapTemplates/killhouse_template.json'
old=json.loads(TARGET.read_text());pieces=[]
ART='/Game/EclipseRecoil/Art/FactoryEnvironment/Meshes/'
def box(center,size,material='Concrete',fixed=False,group=0,jitter=(0,0),role='',mesh=None,rotation=(0,0,0),mirrored=True,anchored=False):
    pieces.append(dict(center=center,size=size,material=material,destructible=not fixed,group=group,jitter=jitter,role=role,fixed_mesh=ART+mesh if mesh else None,mesh_rotation=rotation,mirrored=mirrored,anchored=anchored))
# One base is authored; the opposing base is generated by a half turn.
for x in [-590,590]:box((x,-2600,125),(20,800,250),role='base_side')
# Rear ground entrance is aligned with the internal stair lane at X=250.
for lo,hi in [(-580,150),(350,580)]:box(((lo+hi)/2,-2990,125),(hi-lo,20,250),role='base_rear')
box((250,-2990,237.5),(200,20,25),role='base_rear_lintel')
# Field-facing wall has two firing windows, rather than a front doorway.
for lo,hi in [(-580,-380),(-220,220),(380,580)]:box(((lo+hi)/2,-2210,125),(hi-lo,20,250),role='base_front')
for x in [-300,300]:
    box((x,-2210,50),(160,20,100),role='base_window_sill')
    box((x,-2210,225),(160,20,50),role='base_window_lintel')
# Roof slabs leave a genuine 220x420cm stairwell; roof top=270cm.
for lo,hi in [(-600,140),(360,600)]:box(((lo+hi)/2,-2700,260),(hi-lo,420,20),'Metal',True,role='base_roof',mesh='SM_IndustrialPlatform02')
for lo,hi in [(-3000,-2910),(-2490,-2200)]:box((0,(lo+hi)/2,260),(1200,hi-lo,20),'Metal',True,role='base_roof',mesh='SM_IndustrialPlatform02')
for i in range(14):
    rise=270/14
    box((250,-2895+i*30,(i+.5)*rise),(180,30,rise),'Metal',True,role='base_stair',mesh='SM_PlatformGrill_01')
for x in [-590,590]:box((x,-2600,320),(20,800,100),role='base_roof_parapet',anchored=True)
box((0,-2210,320),(1160,20,100),role='base_roof_parapet',anchored=True)
# Denser staggered fighting lanes, all paired with identical offsets/materials.
for x,y,w,g in [(-1100,-1850,650,10),(1050,-1650,650,11),(-700,-1150,550,12),(650,-1050,500,13)]:
    box((x,y,87.5),(w,30,175),'Concrete',False,g,(100,100),'low_cover')
for x,y,g in [(-650,-1550,20),(650,-1950,21),(-250,-1400,22),(1100,-2800,23),(-1100,-2800,24)]:
    box((x,y,50),(180,120,100),'Wood',False,g,(50,50),'pallet_crates')
    box((x+20,y,125),(100,100,50),'Wood',False,g,(50,50),'pallet_crates')
# Returns create L-shaped cover, rather than a sequence of isolated bars.
box((-1410,-2015,87.5),(30,300,175),'Concrete',False,10,(100,100),'cover_return')
box((1360,-1485,87.5),(30,300,175),'Concrete',False,11,(100,100),'cover_return')
box((-750,-650,50),(300,30,100),'Concrete',False,30,(100,100),'container_screen')
box((-1200,-1450,75),(200,180,150),'Metal',True,12,(100,100),'industrial_tank',mesh='SM_WaterContainer01')
# Whole cargo container and closed industrial tanks, with matched counterparts.
box((-1150,-500,150),(300,650,300),'Metal',True,30,(100,100),'container',mesh='SM_Container01_01')
box((700,-500,90),(240,320,180),'Metal',True,31,(100,100),'industrial_tank',mesh='SM_WaterContainer01')
for x,y in [(500,-700),(800,-750)]:box((x,y,50),(70,70,100),'Metal',True,31,(100,100),'barrel',mesh='SM_Barrel02')
# Central watch tower, with access stairs at both ends.
for x in [-185,185]:box((x,-235,150),(30,30,300),'Metal',True,role='tower_column',mesh='SM_PlatformPillar_01')
box((0,0,310),(450,550,20),'Metal',True,role='tower_platform',mesh='SM_IndustrialPlatform02',mirrored=False)
for i in range(16):box((0,-740+i*30,(i+.5)*20),(150,30,20),'Metal',True,role='tower_stair',mesh='SM_PlatformGrill_01')
box((215,0,370),(20,550,100),'Metal',True,role='tower_guard',mesh='SM_MetalWallPart_01')
# Roof trusses and paired industrial columns. Keep the patrol lane at +/-1750.
for y in [-3500,-2500,-1500,-500]:
    box((0,y,1020),(4100,30,60),'Metal',True,role='roof_beam',mesh='SM_MetalBeam15')
    for x in [-2025,2025]:box((x,y,490),(50,50,980),'Metal',True,role='shell_column',mesh='SM_MetalBeam10')
alpha=old['spawns']['alpha'];omega=[]
for s in alpha:omega.append(dict(position=[-s['position'][0],-s['position'][1],s['position'][2]],yaw=s['yaw']+180))
data=dict(schema=2,id='killhouse_industrial',revision=2,source=old['source'],symmetry='HalfTurn',arena_size=old['arena_size'],spawns=dict(alpha=alpha,omega=omega),patrol_route=[[-1750,-3500,100],[-1750,0,100],[-1750,3500,100],[1750,3500,100],[1750,0,100],[1750,-3500,100]],shell_wall_mesh=ART+'SM_MetalWallPart_02',roof_mesh=ART+'SM_MetalWallPart_02',pieces=pieces)
# Validate nominal assembly volumes before an Unreal data asset can be touched.
volumes=[]
for i,p in enumerate(pieces):
    for sign in ([1,-1] if p['mirrored'] else [1]):
        c=[p['center'][0]*sign,p['center'][1]*sign,p['center'][2]]
        for j,other,sz in volumes:
            overlap=[min(c[k]+p['size'][k]/2,other[k]+sz[k]/2)-max(c[k]-p['size'][k]/2,other[k]-sz[k]/2) for k in range(3)]
            if min(overlap)>.01:raise ValueError('Overlapping assembly pieces '+str((i,p['role'],j,overlap)))
        volumes.append((i,c,p['size']))
TARGET.write_text(json.dumps(data,indent=2)+'\n')
print('KILLHOUSE_MANIFEST_BALANCED authored='+str(len(pieces))+' generated='+str(len(volumes)))
